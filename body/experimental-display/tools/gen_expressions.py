#!/usr/bin/env python3
"""Generate src/face/expressions_data.h from src/face/expressions.json (the source of truth)."""
import json, os, sys

REQUIRED = ["curve", "width", "open", "corner", "cheek", "eye", "brow", "tilt"]
OPTIONAL = {"lid": 0}          # added for the happy closed-eye arcs; absent => 0, so existing presets are unchanged
FIELDS = REQUIRED + list(OPTIONAL)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "src", "face", "expressions.json")
dst = os.path.join(root, "src", "face", "expressions_data.h")

data = json.load(open(src))
exprs = data["expressions"]
names = list(exprs.keys())
for n in names:
    if not n.isidentifier():
        sys.exit(f"expression name {n!r} is not a valid C++ identifier")
    for k, dv in OPTIONAL.items():
        exprs[n].setdefault(k, dv)
    missing = [f for f in REQUIRED if f not in exprs[n]]
    extra = [f for f in exprs[n] if f not in FIELDS]
    if missing or extra:
        sys.exit(f"{n}: missing={missing} extra={extra}")

def num(v):
    return repr(float(v)).rstrip("0").rstrip(".") + "f" if float(v) != int(v) else f"{int(v)}.f"

out = [
    "// GENERATED by tools/gen_expressions.py from src/face/expressions.json -- do not edit.",
    "#pragma once",
    '#include "FaceTypes.h"',
    "",
    "namespace sunday {",
    "",
    f"// JSON version {data['version']}, character {data['character']}",
    "enum class ExprId : uint8_t { " + ", ".join(names) + " };",
    f"static constexpr int kExpressionCount = {len(names)};",
    "",
    "static constexpr const char* kExpressionNames[kExpressionCount] = {",
    ",\n".join(f'    "{n}"' for n in names),
    "};",
    "",
    "// order: " + ", ".join(FIELDS),
    "static constexpr ExpressionParams kExpressions[kExpressionCount] = {",
    "\n".join("    {" + ", ".join(num(exprs[n][f]) for f in FIELDS) + "},  // " + n for n in names),
    "};",
    "",
    "}  // namespace sunday",
    "",
]
text = "\n".join(out)
if not os.path.exists(dst) or open(dst).read() != text:
    open(dst, "w").write(text)
    print("generated", dst)
